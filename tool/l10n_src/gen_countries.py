"""Generates lib/data/countries.dart (Uzbek country name -> flag) from the
data generators' flag tables, plus a few extra countries."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / 'tool'))
from efl_data import FLAG  # noqa: E402

EXTRA = {
    'Qozog‘iston': '🇰🇿', 'Turkmaniston': '🇹🇲', 'Ozarbayjon': '🇦🇿', 'Afg‘oniston': '🇦🇫', 'Xitoy': '🇨🇳',
    'Hindiston': '🇮🇳', 'Saudiya Arabistoni': '🇸🇦', 'BAA': '🇦🇪', 'Qatar': '🇶🇦', 'Pokiston': '🇵🇰',
    'Peru': '🇵🇪', 'Boliviya': '🇧🇴', 'Kosta-Rika': '🇨🇷', 'Gonduras': '🇭🇳', 'Kuba': '🇨🇺', 'Ruminiya': '🇷🇴',
    'Moldova': '🇲🇩', 'Belarus': '🇧🇾', 'Litva': '🇱🇹', 'Latviya': '🇱🇻', 'Estoniya': '🇪🇪', 'Lyuksemburg': '🇱🇺',
    'Avstraliya': '🇦🇺', 'Mo‘g‘uliston': '🇲🇳', 'Tailand': '🇹🇭', 'Vyetnam': '🇻🇳', 'Malayziya': '🇲🇾',
}
FIRST = ['O‘zbekiston', 'Qozog‘iston', 'Tojikiston', 'Qirg‘iziston', 'Turkmaniston', 'Rossiya', 'Angliya']


def main():
    flags = {**FLAG, **EXTRA}
    flags.pop('Shimoliy Irlandiya', None)
    flags['Shimoliy Irlandiya'] = '🇬🇧'
    names = FIRST + sorted((n for n in flags if n not in FIRST), key=lambda n: n.replace('‘', '').lower())
    lines = ["/// Nationalities offered in the manager and player creators (Uzbek",
             "/// names are data keys; they are translated where displayed).",
             "/// Generated by tool/l10n_src/gen_countries.py.",
             "const countryFlags = <String, String>{"]
    for n in names:
        lines.append(f"  '{n}': '{flags[n]}',")
    lines.append('};')
    (ROOT / 'lib' / 'data' / 'countries.dart').write_text('\n'.join(lines) + '\n', encoding='utf8')
    print(len(names), 'countries')


if __name__ == '__main__':
    main()
